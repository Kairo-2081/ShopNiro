const maxCvBytes = 3 * 1024 * 1024;

function requireGroq() {
  if (!groq) {
    const error = new Error('AI CV assistance is unavailable. Please enter the information manually.');
    (error as Error & { statusCode?: number }).statusCode = 503;
    throw error;
  }
}

function decodePdf(value: unknown): Buffer {
  if (typeof value !== 'string') throw new Error('Upload a PDF CV to continue.');
  const base64 = value.replace(/^data:application\/pdf;base64,/, '');
  const buffer = Buffer.from(base64, 'base64');
  if (!buffer.length || buffer.length > maxCvBytes || buffer.subarray(0, 4).toString() !== '%PDF') {
    throw new Error('CV must be a valid PDF file under 3 MB.');
  }
  return buffer;
}

function parseJsonResponse(value: string): Record<string, unknown> {
  const start = value.indexOf('{');
  const end = value.lastIndexOf('}');
  if (start < 0 || end < start) throw new Error('AI returned an unreadable CV result. Please fill the fields manually.');
  return JSON.parse(value.slice(start, end + 1));
}

function cleanList(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((item): item is string => typeof item === 'string').map((item) => item.trim()).filter(Boolean).slice(0, 20) : [];
}

function hasMapCoordinates(address: any): boolean {
  return Number.isFinite(Number(address?.Latitude)) && Number(address.Latitude) >= -90 && Number(address.Latitude) <= 90 &&
    Number.isFinite(Number(address?.Longitude)) && Number(address.Longitude) >= -180 && Number(address.Longitude) <= 180;
}

function addressSignature(value: unknown): string {
  const address = typeof value === 'string' ? JSON.parse(value) : (value || {}) as Partial<Address>;
  const coordinate = (number: unknown) => number === null || number === undefined || number === '' || !Number.isFinite(Number(number)) ? null : Number(number);
  return JSON.stringify([
    address.House_Name || '', address.Street || '', address.City || '', address.Postal_Code || '',
    address.Additional_Info || '', coordinate(address.Latitude), coordinate(address.Longitude),
  ]);
}

function createRiderCvPdf(profile: { name: string; email: string; phone: string; presentAddress: Address; permanentAddress: Address; experience: string[]; previousJobs: string[]; education: string[] }): Promise<Buffer> {
  return new Promise((resolvePdf, reject) => {
    const document = new PDFDocument({ size: 'A4', margin: 54, info: { Title: `${profile.name} | ShopNiro Rider CV`, Author: 'ShopNiro' } });
    const chunks: Buffer[] = [];
    document.on('data', (chunk: Buffer) => chunks.push(chunk));
    document.on('end', () => resolvePdf(Buffer.concat(chunks)));
    document.on('error', reject);

    const pageWidth = 595.28;
    const left = 54;
    const contentWidth = 487;
    const right = left + contentWidth;
    const drawRunningHeader = () => {
      document.fillColor('#807653').font('Helvetica-Bold').fontSize(8).text('SHOPNIRO  /  RIDER PROFILE', left, 32, { characterSpacing: 0.8 });
      document.moveTo(left, 48).lineTo(right, 48).lineWidth(0.7).strokeColor('#e8e6df').stroke();
    };
    const drawFooter = () => {
      document.moveTo(left, 790).lineTo(right, 790).lineWidth(0.7).strokeColor('#e8e6df').stroke();
      document.fillColor('#858275').font('Helvetica').fontSize(8).text('Generated by ShopNiro Delivery Operations', left, 800);
      document.fillColor('#858275').font('Helvetica').fontSize(8).text('Professional profile', left, 800, { width: contentWidth, align: 'right' });
    };

    document.rect(0, 0, pageWidth, 166).fill('#10100f');
    document.rect(0, 162, pageWidth, 4).fill('#aaa17e');
    document.image(resolve(process.cwd(), 'ShopNiro-new-round-final.png'), left, 34, { fit: [56, 56] });
    document.fillColor('#ffffff').font('Times-Bold').fontSize(22).text('ShopNiro', 124, 39);
    document.fillColor('#c9c5b7').font('Helvetica').fontSize(9).text('MARKETPLACE  /  DELIVERY OPERATIONS', 125, 67, { characterSpacing: 0.7 });
    document.fillColor('#c9c5b7').font('Helvetica-Bold').fontSize(8).text('RIDER CURRICULUM VITAE', left, 101, { characterSpacing: 1.1 });
    document.fillColor('#ffffff').font('Times-Bold').fontSize(24).text(profile.name, left, 117, { width: contentWidth, height: 34, ellipsis: true });

    let y = 190;
    const nextPage = () => {
      drawFooter();
      document.addPage();
      drawRunningHeader();
      y = 66;
    };
    const addressText = (address: Address) => [address.House_Name, address.Street, address.City, address.Postal_Code]
      .filter(Boolean).join(', ') || 'Not provided';
    const section = (title: string, entries: string[]) => {
      if (!entries.length) return;
      if (y + 38 > 770) nextPage();
      document.fillColor('#807653').font('Helvetica-Bold').fontSize(9).text(title.toUpperCase(), left, y, { characterSpacing: 1 });
      y += 17;
      document.moveTo(left, y).lineTo(right, y).lineWidth(0.7).strokeColor('#e8e6df').stroke();
      y += 11;
      for (const entry of entries) {
        document.font('Helvetica').fontSize(10);
        const height = document.heightOfString(entry, { width: contentWidth - 17, lineGap: 3 });
        if (y + height > 770) nextPage();
        document.circle(left + 3, y + 6, 2).fill('#aaa17e');
        document.fillColor('#37362e').font('Helvetica').fontSize(10).text(entry, left + 14, y, { width: contentWidth - 17, lineGap: 3 });
        y += height + 8;
      }
      y += 9;
    };

    section('Contact', [profile.email, profile.phone]);
    section('Present address', [addressText(profile.presentAddress)]);
    section('Permanent address', [addressText(profile.permanentAddress)]);
    section('Relevant experience', profile.experience);
    section('Previous employment', profile.previousJobs);
    section('Education and qualifications', profile.education);
    drawFooter();
    document.end();
  });
}

const riderCvFileName = (name: string) => `${name.replace(/[^a-zA-Z0-9-_]+/g, '-').replace(/-+/g, '-').slice(0, 100) || 'rider'}-ShopNiro-CV.pdf`;

async function regenerateStoredRiderCv(riderId: string) {
  const result = await query(`
    SELECT r.name, r.number, r.present_address_json, r.permanent_address_json,
      r.experience_json, r.previous_jobs_json, r.education_json, u.email
    FROM riders r JOIN users u ON u.id = r.id WHERE r.id = $1
  `, [riderId]);
  if (!result.rows.length) return null;
  const row = result.rows[0];
  const address = (value: any): Address => typeof value === 'string' ? JSON.parse(value) : value || {};
  const fileName = riderCvFileName(String(row.name || 'Rider'));
  const buffer = await createRiderCvPdf({
    name: String(row.name || ''),
    email: String(row.email || ''),
    phone: String(row.number || ''),
    presentAddress: address(row.present_address_json),
    permanentAddress: address(row.permanent_address_json),
    experience: cleanList(row.experience_json),
    previousJobs: cleanList(row.previous_jobs_json),
    education: cleanList(row.education_json),
  });
  await query('UPDATE riders SET has_cv = TRUE, cv_file_name = $2, cv_pdf = $3 WHERE id = $1', [riderId, fileName, buffer]);
  return { fileName, buffer };
}

function mapRider(row: any): Rider {
  const points = Number(row.current_month_performance_points ?? row.performance_points);
  return {
    Rider_ID: row.id,
    Username: row.username || '',
    Name: row.name,
    Email: row.email || '',
    Number: row.number || '',
    Present_Address: row.present_address_json || {},
    Permanent_Address: row.permanent_address_json || {},
    Experience: cleanList(row.experience_json),
    Previous_Jobs: cleanList(row.previous_jobs_json),
    Education: cleanList(row.education_json),
    Status: row.status,
    Has_CV: Boolean(row.has_cv),
    CV_File_Name: row.cv_file_name || undefined,
    Current_Latitude: row.current_latitude === null ? undefined : Number(row.current_latitude),
    Current_Longitude: row.current_longitude === null ? undefined : Number(row.current_longitude),
    Total_Deliveries: Number(row.total_deliveries) || 0,
    Timely_Deliveries: Number(row.timely_deliveries) || 0,
    Late_Deliveries: Number(row.late_deliveries) || 0,
    Performance_Points: Number.isFinite(points) ? points : 100,
    Average_Rating: Number(row.average_rating) || 0,
    Wallet_Balance: Number(row.wallet_balance) || 0,
    Created_At: row.created_at ? new Date(row.created_at).toISOString() : new Date().toISOString(),
  };
}

router.post('/cv/parse', async (req, res) => {
  try {
    requireGroq();
    const pdfBuffer = decodePdf(req.body?.cvBase64);
    const pdf = await pdfParse(pdfBuffer);
    const text = pdf.text.replace(/\s+/g, ' ').trim().slice(0, 45000);
    if (text.length < 40) return res.status(422).json({ error: 'This PDF has no readable text. Please enter your work and education details manually.' });

    const aiResult = await groq!.chat.completions.create({
      model: process.env.GROQ_MODEL_FAST?.trim() || 'openai/gpt-oss-20b',
      temperature: 0.1,
      messages: [
        { role: 'system', content: 'Extract only facts explicitly present in the CV. Return one JSON object with string-array fields experience, previousJobs, and education. Use empty arrays for missing information. Do not infer facts.' },
        { role: 'user', content: text },
      ],
    });
    const parsed = parseJsonResponse(aiResult.choices[0]?.message?.content || '');
    const extracted = {
      experience: cleanList(parsed.experience),
      previousJobs: cleanList(parsed.previousJobs),
      education: cleanList(parsed.education),
    };
    const missingFields = Object.entries(extracted).filter(([, values]) => values.length === 0).map(([field]) => field);
    return res.json({ extracted, missingFields });
  } catch (error: any) {
    const statusCode = error?.statusCode || 400;
    return res.status(statusCode).json({ error: error.message || 'Could not read this CV.' });
  }
});


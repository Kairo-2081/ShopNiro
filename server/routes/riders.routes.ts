router.post('/apply', async (req, res) => {
  const {
    Username,
    Name,
    Email,
    Password,
    Number: phone,
    Present_Address,
    Permanent_Address,
    Has_CV,
    CV_Base64,
    CV_File_Name,
    Experience,
    Previous_Jobs,
    Education,
  } = req.body ?? {};

  if (![Username, Name, Email, Password, phone].every((value) => typeof value === 'string' && value.trim())) {
    return res.status(400).json({ error: 'Name, username, email, password, and phone number are required.' });
  }
  if (String(Password).length < 8) return res.status(400).json({ error: 'Password must be at least 8 characters.' });
  if (typeof Has_CV !== 'boolean') {
    return res.status(400).json({ error: 'Choose whether you have a CV.' });
  }
  if (
    !Present_Address?.Street || !Present_Address?.City || !Permanent_Address?.Street || !Permanent_Address?.City ||
    !hasMapCoordinates(Present_Address) || !hasMapCoordinates(Permanent_Address)
  ) {
    return res.status(400).json({ error: 'Select map locations and complete both present and permanent addresses.' });
  }

  if (Has_CV && !CV_Base64) {
    return res.status(400).json({ error: 'Upload your PDF CV to continue.' });
  }
  if (Has_CV) {
    try {
      decodePdf(CV_Base64);
    } catch (error: any) {
      return res.status(400).json({ error: error.message });
    }
  }

  const experience = cleanList(Experience);
  const previousJobs = cleanList(Previous_Jobs);
  const education = cleanList(Education);
  let cvBuffer: Buffer;
  try {
    cvBuffer = await createRiderCvPdf({
      name: String(Name).trim(),
      email: String(Email).trim().toLowerCase(),
      phone: String(phone).trim(),
      presentAddress: Present_Address as Address,
      permanentAddress: Permanent_Address as Address,
      experience,
      previousJobs,
      education,
    });
  } catch (error) {
    console.error('Could not generate rider CV PDF:', error);
    return res.status(500).json({ error: 'Could not generate your rider CV PDF. Please try again.' });
  }
  const cvFileName = `${String(Name).trim().replace(/[^a-zA-Z0-9-_]+/g, '-').replace(/-+/g, '-').slice(0, 100) || 'rider'}-ShopNiro-CV.pdf`;

  const client = await pool.connect();
  try {
    const riderId = `RDR-${Date.now()}-${Math.floor(1000 + Math.random() * 9000)}`;
    const username = String(Username).trim().toLowerCase();
    const email = String(Email).trim().toLowerCase();
    await client.query('BEGIN');
    const duplicate = await client.query(
      'SELECT 1 FROM users WHERE lower(email) = $1 OR lower(username) = $2 LIMIT 1',
      [email, username]
    );
    if (duplicate.rows.length) {
      await client.query('ROLLBACK');
      return res.status(409).json({ error: 'That email or username is already registered.' });
    }
    await client.query(
      'INSERT INTO users (id, username, password, email, role) VALUES ($1, $2, $3, $4, $5)',
      [riderId, username, await hashPassword(String(Password)), email, 'rider']
    );
    await client.query(
      `INSERT INTO riders (
        id, name, number, status, present_address_json, permanent_address_json,
        has_cv, cv_file_name, cv_pdf, experience_json, previous_jobs_json, education_json
      ) VALUES ($1, $2, $3, 'pending', $4::jsonb, $5::jsonb, $6, $7, $8, $9::jsonb, $10::jsonb, $11::jsonb)`,
      [
        riderId,
        String(Name).trim(),
        String(phone).trim(),
        JSON.stringify(Present_Address as Address),
        JSON.stringify(Permanent_Address as Address),
        true,
        cvFileName,
        cvBuffer,
        JSON.stringify(experience),
        JSON.stringify(previousJobs),
        JSON.stringify(education),
      ]
    );
    await client.query('COMMIT');
    return res.status(201).json({ success: true, status: 'pending', message: 'Application received. Your ShopNiro CV PDF has been generated and saved. An administrator must approve your rider account before delivery operations are available.' });
  } catch (error: any) {
    await client.query('ROLLBACK');
    console.error('Rider application failed:', error);
    return res.status(500).json({ error: 'Could not submit rider application.' });
  } finally {
    client.release();
  }
});

